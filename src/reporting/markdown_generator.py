"""Markdown report for humans. All dynamic text is Markdown-escaped."""
from typing import Any

from src.utils.text import md_escape

PCT = lambda v: "N/A" if v is None else f"{v:.1f}%"  # noqa: E731


def render_markdown(audit: dict[str, Any]) -> str:
    meta, metrics, disc = audit["audit"], audit["metrics"], audit["discovery"]
    ci, sec, env = audit["ci_statistics"], audit["security_statistics"], audit["environment_statistics"]
    br = audit["branch_protection"]
    lines = [
        f"# Organization health: {md_escape(audit['organization'])}",
        "",
        f"Generated by DevOps-Control-Center. Status **{meta['status']}**, completeness {PCT(meta['completeness_percent'])}.",
        "",
        f"- Audit run: `{md_escape(meta['run_id'])}`",
        f"- Timestamp (UTC): `{md_escape(meta['timestamp'])}`",
        f"- Mode: `{md_escape(meta['mode'])}`, authentication: `{md_escape(meta['auth_mode'])}`",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Repositories discovered | {disc['total_discovered']} |",
        f"| Repositories audited | {disc['audited']} |",
        f"| Excluded | {disc['excluded']} |",
        f"| Healthy | {metrics['healthy']} |",
        f"| Warning | {metrics['warning']} |",
        f"| Failed | {metrics['failed']} |",
        f"| Without CI/CD | {metrics['no_ci']} |",
        f"| Unknown | {metrics['unknown']} |",
        f"| Organization health | {PCT(metrics['health_percent'])} |",
        "",
        "## CI/CD",
        "",
        f"- Repositories with a concluded latest run: {ci['evaluated']}",
        f"- Latest run succeeded: {ci['latest_success']} ({PCT(ci['success_percent'])})",
        f"- Latest run failed: {ci['latest_failed']}",
        f"- Repeated failures: {ci['repeated_failures']}",
        "",
        "## Branch protection",
        "",
        f"- Evaluated: {br['evaluated']}, compliant: {br['compliant']}, non-compliant: {br['non_compliant']} ({PCT(br['compliance_percent'])})",
        f"- Scope: `{md_escape(br['scope'])}`",
        "",
        "## Environments and secrets",
        "",
        f"- Configured: {env['configured']}, not configured: {env['not_configured']}, warnings: {env['warnings']}",
        f"- Coverage: {PCT(env['coverage_percent'])}",
        f"- Organization secrets (count only): {env['organization_secrets'].get('secret_count', 'unavailable')}",
        "",
        "## Security",
        "",
        f"- Covered (secret scanning and Dependabot visible): {sec['covered']} ({PCT(sec['coverage_percent'])})",
        f"- Critical or high findings: {sec['critical']}; warnings: {sec['warning']}",
        f"- Open Dependabot alerts: {sec['open_dependabot_alerts']}; open code scanning alerts: {sec['open_code_scanning_alerts']}",
        "",
        "## Repositories",
        "",
        "| Repository | Visibility | CI/CD | Security | Branch | Environment | Overall |",
        "|---|---|---|---|---|---|---|",
    ]
    for repo in audit["repositories"]:
        lines.append(
            f"| {md_escape(repo['name'])} | {md_escape(repo['visibility'])} | {repo['ci']['status']} | "
            f"{repo['security']['status']} | {repo['branch']['status']} | {repo['environment']['status']} | "
            f"**{repo['overall']}** |"
        )
    lines += ["", "## Latest failures", ""]
    if audit["latest_failures"]:
        for failure in audit["latest_failures"]:
            jobs = ", ".join(md_escape(j) for j in failure["failed_jobs"]) or "none listed"
            lines.append(f"- {md_escape(failure['repository'])}: {failure['conclusion']} "
                         f"({failure['consecutive_failures']} consecutive); failed jobs: {jobs}")
    else:
        lines.append("No failing latest runs in this audit.")
    lines += ["", "## Recommendations", ""]
    for rec in audit["recommendations"]:
        lines.append(f"- **{rec['priority'].upper()}**: {md_escape(rec['message'])}")
    if not audit["recommendations"]:
        lines.append("No recommendations for this audit.")
    lines += ["", "## Audit completeness and API limitations", ""]
    lines.append(f"- Checks completed: {audit['completeness']['checks_completed']} of {audit['completeness']['checks_total']}")
    for item in audit.get("api_limitations", []):
        lines.append(f"- {md_escape(item['message'])} (repositories affected: {item['repositories']})")
    if not audit.get("api_limitations"):
        lines.append("- No API limitations recorded.")
    lines += ["", "Automatically generated by DevOps-Control-Center.", ""]
    return "\n".join(lines)
